export const uiCopy = (language: Language) => copy[language];
export function localizedError(error: string, language: Language) {
  if (
    !error ||
    language === "en-IN" ||
    /[\u0900-\u097f\u0c80-\u0cff]/u.test(error)
  )
    return error;
  const c = copy[language];
  const rules: [RegExp, string][] = [
    [/saved contact|saved recipient/i, c.changed],
    [/OTP|financial secret|password|UPI PIN/i, c.secret],
    [/confirmation|review.*again/i, c.confirmation],
    [/expired|session/i, c.expired],
    [/unresolved|matching payment|duplicate/i, c.duplicate],
    [/UPI|payment address/i, c.upiError],
    [/mobile|phone|10–15|10-15/i, c.phoneError],
    [/not found|not available|no longer/i, c.notAvailable],
    [/too many|rate.limit|wait|busy|later/i, c.busy],
    [/reach|connect|unavailable|network|timeout/i, c.lostNetwork],
  ];
  return rules.find(([pattern]) => pattern.test(error))?.[1] ?? c.invalid;
}

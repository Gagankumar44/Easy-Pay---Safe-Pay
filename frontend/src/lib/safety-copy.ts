export function safetyCopy(
  language: Language,
  signal: Safety["signals"][number],
) {
  const translated =
    language === "en-IN"
      ? undefined
      : copy[signal.code]?.[language === "hi-IN" ? "hi" : "kn"];
  return translated
    ? { noticed: translated[0], action: translated[1] }
    : signal;
}
